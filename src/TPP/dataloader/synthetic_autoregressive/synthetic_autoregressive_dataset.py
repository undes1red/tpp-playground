def insert(per_line, number):
    return np.concatenate([np.array([number]), per_line])

def diff(per_line, shift):
    '''
    Avoid potential 0 output.
    '''
    return np.diff(per_line) + (1e-6 if shift else 0)

class SynAregDataset(utils.data.Dataset):
    '''
    Self defined dataset. The required pandas DataFrame are listed in train.py.
    But...what can we do if we need prediction? It is strange.
    '''

    def __init__(self, data, device, num_events, history_length = 2, plot = False, shift = False, shift_time = False, input_norm_data = False):
        super(SynAregDataset, self).__init__()
        self.data = data
        self.device = device
        self.plot = plot
        self.num_events = num_events
        self.history_length = history_length
        self.mean = 0
        self.var = 1

        # Data preprocessing
        if shift_time:
            '''
            Current stackoverflow specific
            '''
            for idx, item in enumerate(self.data.time_seq):
                first_event_abs_time = item[0]
                self.data.time_seq[idx].insert(0, first_event_abs_time - 0.8)
        else:
            self.data.time_seq = self.data.time_seq.apply(insert, number = 0)

        self.data.time_seq = self.data.time_seq.apply(diff, shift = shift)
        # if input_norm_data:
        #     self.data.time_seq = self.data.time_seq.apply(math.log)
        self.data.time_seq = self.data.time_seq.apply(insert, number = 0)
        self.data.event = self.data.event.apply(insert, number = self.num_events)
        self.data.score = self.data.score.apply(insert, number = 0)
        self.data.intensity = self.data.intensity.apply(insert, number = 0)

        # Data normalization
        # We need it because several datasets' inputs are just so huge that several model can never handle it.
        if input_norm_data:
            regenerated_data = pd.DataFrame(self.data['time_seq'].values.tolist())
            regenerated_data = (regenerated_data + 1e-8).stack()
            self.mean = regenerated_data.mean()
            self.var = regenerated_data.std()

        '''
        Transferred data:
        1. 'history': The history.
        2. 'result': The result that model should infer based on the history.
        3. 'score': The ideal loss value.
        4. 'event': event type. Will be discarded if the model have event_toggle = False.
        5. 'intensity': intensity. Used by plotters.
        '''
        self.data = transform_autoregression(data, self.history_length, num_events)

        self.data.history_time = self.data.history_time.apply(np.array, dtype = np.float32)
        self.data.history_event = self.data.history_event.apply(np.array, dtype = np.int32)
        self.data.result = self.data.result.apply(np.array, dtype = np.float32)
        self.data.score = self.data.score.apply(np.array, dtype = np.float32)
        self.data.event = self.data.event.apply(np.array, dtype = np.int32)
        self.data.intensity = self.data.intensity.apply(np.array, dtype = np.float32)


    def __getitem__(self, index):
        '''
        Synthetic dataloader is very simple. It doesn't have any event infomation at each timestamp,
        and only the time differences between two neighboring events are available.
        '''
        if isinstance(index, slice):
            return [
                self[idx] for idx in range(index.start or 0, index.stop or len(self), index.step or 1)
            ]
        else:
            if self.plot:
                return self.data.iloc[index].history_time, \
                       self.data.iloc[index].history_event, \
                       self.data.iloc[index].result, \
                       self.data.iloc[index].score, \
                       self.data.iloc[index].event, \
                       self.data.iloc[index].intensity
            else:
                return self.data.iloc[index].history_time, \
                       self.data.iloc[index].history_event, \
                       self.data.iloc[index].result, \
                       self.data.iloc[index].score, \
                       self.data.iloc[index].event


    def __len__(self):
        return self.data.shape[0]
    

    def __call__(self, data):
        '''
        Each item in input data:
        [history_time, history_event, result, score, event, intensity if self.plot else it doesn't exist at all.]

        The structure of data:
        [
            (history_time, history_event, result, score, event, intensity if self.plot else it doesn't exist at all., mask)
        ],
        (mean, var)

        For SynAregDataset, the padding events generated by transform_autoregression() should be masked out. 0 means this item should
        be masked out.
        '''
        padded_data = []
        max_length_of_this_batch = max([item[0].shape[0] for item in data])
        for item in data:
            current_data_size = item[2].size
            # pad history_time, history_event, result, score, event, and intensity when max_length_of_this_batch > current_length
            padded_item = []
            padded_item.append(np.pad(item[0], pad_width=((max_length_of_this_batch - current_data_size, 0), (0, 0)), mode = 'minimum'))
            padded_item.append(np.pad(item[1], pad_width=((max_length_of_this_batch - current_data_size, 0), (0, 0)), mode = 'constant', constant_values = self.num_events + 1))
            padded_item.append(np.pad(item[2], pad_width=((max_length_of_this_batch - current_data_size, 0)), mode = 'constant', constant_values = 0))
            padded_item.append(np.pad(item[3], pad_width=((max_length_of_this_batch - current_data_size, 0)), mode = 'constant', constant_values = 0))
            padded_item.append(np.pad(item[4], pad_width=((max_length_of_this_batch - current_data_size, 0)), mode = 'constant', constant_values = self.num_events + 1))
            if self.plot:
                padded_item.append(np.pad(item[5], pad_width=((max_length_of_this_batch - current_data_size, 0)), mode = 'constant', constant_values = 0))

            mask = np.array(padded_item[1] <= self.num_events).astype(int)
            padded_item = [*padded_item, mask]
            padded_data.append(tuple(padded_item))
        
        from torch.utils.data._utils.collate import default_collate
        padded_data = default_collate(padded_data)
        if self.plot:
            move = move_data_to_the_correct_device(device = self.device)
            padded_data = move.move_to_device(padded_data)
        
        return padded_data, (self.mean, self.var)


def read_data(path, file_names):
    data_raw = {}
    is_csv = file_names[0].split('.')[-1] == 'csv'
    try:
        if is_csv:
            for file_name in file_names:
                file, type = file_name.split('.')
                data_raw[file] = pd.read_csv(
                    os.path.join(path, file + '.' + type))
        else:
            for file_name in file_names:
                file, type = file_name.split('.')
                data_raw[file] = pd.read_json(
                    os.path.join(path, file + '.' + type))
    except:
        raise TypeError(
            f"Wrong datafile format. Please check your data file in {path}")
    
    return data_raw

def synarg_dataloader():
    '''
    Synthetic dataloader for all synthetic datasets.
    '''
    return [SynAregDataset, read_data]