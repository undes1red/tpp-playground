from src.TPP.utils import getLogger


logger = getLogger(name = __file__)

'''
This is the main plotter library.
For all tpp models waiting for being evaluated, you should have two methods implemented.
1. function_prober(data, resolution):
Args:
   1. data: The fresh raw data from the corresponding dataloader. Batch size is 1 and can not be changed.
   2. resolution: It elabrates how many additional time points are inserted between two events. In fact, because
                  new time points are generated by torch.linspace(0, 1, resolution) * time, there are only
                  (resolution - 2) new points.
Output:
   If this model is present in list named 'intensity_available', its function_prober() should have three kinds of outputs.
   1. integral: the values of the intensity integral function at all probing points.
   2. intensity: the values of the intensity function at all probing points.
   3. timestamp: cumulative timestamps of all points that have been used during model distribution estimation.
   Otherwise, it should have two kinds of outputs.
   1. probability: the values of the probability distribution at all probing points.
   2. timestamp: cumulative timestamps of all points that have been used during model distribution estimation.
Function behaviours:
This function should return

2. model_prober
'''

def draw(model, minibatch, desc, batch_idx, opt):
    '''
    This function is for model probing. It can be super useful when you need to dig into a model and see
    what really happens.
    data: [time_diff, score, target_intensity]
    '''

    '''
    In the new pipeline, each plot is defined as a instruction list. draw_features() should extract and
    call correct seaborn APIs from each plot dict. The structure of the 'plots dict goes as follows:
    {
        ...
        '[plot name]':
        [
            ...
            {
                'plot_type': '[plot_type]'
                'length': [diagram length],
                'height': [diagram height],
                'kwargs':
                {
                    ...'[arguments sent to seaborn APIs.]'
                }
            }
            ...
        ]
        ...
    }
    '''

    plots = model.plot(minibatch, opt)
    
    # Create the plot storing directory if not exist.
    plot_store_dir_for_this_batch = os.path.join(opt.store_dir, opt.plot_type, desc, str(batch_idx))
    if not os.path.exists(plot_store_dir_for_this_batch):
        os.makedirs(plot_store_dir_for_this_batch)
    
    for plot_name, plot_instructions in plots.items():
        fig = plt.figure()
        ax = None
        for instruction in plot_instructions:
            if instruction.get('plot_type') == 'text':
                ax.text(**instruction['kwargs'])
            else:
                if instruction.get('length') and instruction.get('height'):
                    fig.set_size_inches(instruction.get('length'), instruction.get('height'))
                ax = getattr(sns, instruction['plot_type'])(ax = ax, **instruction['kwargs'])
        
        logger.info(f'{plot_name} for No.{batch_idx} minibatch in {desc} dataset finished drawing!')
        plt.savefig(os.path.join(plot_store_dir_for_this_batch, plot_name + '.png'), dpi = 1000)
        plt.close(fig = fig)


def spearman_and_l1(model, dataset, desc, opt):
    spearman = 0
    l1 = 0
    size_of_dataset = len(dataset)
    for minibatch in tqdm(dataset, desc = f'Spearman and L1 for {desc}'):
        spearman_for_this_batch, l1_for_this_batch = model.get_spearman_and_l1(minibatch, opt)               
                                                                               # [batch_size, seq_len * resolution]
        spearman += spearman_for_this_batch
        l1 += l1_for_this_batch
    
    spearman = spearman / size_of_dataset
    l1 = l1 / size_of_dataset

    if not os.path.exists(opt.store_dir):
        os.makedirs(opt.store_dir)
    result_file = os.path.join(opt.store_dir, f'{desc}_spearman_and_l1.txt')
    f = open(result_file, 'w')
    f.write(f'For the {desc} of {opt.dataset_name}, we announce that the average spearman coefficient is {spearman} and average L1 distance is {l1}.')
    f.close()


def mae_and_f1(model, dataset, desc, opt):
    mae = None
    f1 = 0
    size_of_dataset = len(dataset)
    for minibatch in tqdm(dataset, desc = f'MAE and macro-f1 for {desc}'):
        mae_per_seq, f1_per_seq = model.get_mae_and_f1(minibatch, opt)         # [batch_size, seq_len]
        if mae is None:
            mae = mae_per_seq
        else:
            mae, mae_ps = pack((mae, mae_per_seq), '* s')
        f1 += f1_per_seq
    
    f1 = f1 / size_of_dataset
    mean_mae = mae.mean().item()

    if not os.path.exists(opt.store_dir):
        os.makedirs(opt.store_dir)
    result_file = os.path.join(opt.store_dir, f'{desc}_mae_and_macro-f1.txt')
    f = open(result_file, 'w')
    f.write(f'For the {desc} of {opt.dataset_name}, we announce that the average MAE is {mean_mae} and average macro-F1 is {f1}.')
    f.close()


